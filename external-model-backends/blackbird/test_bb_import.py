#!/usr/bin/env python3
"""Tests for bb_import.py, run against the REAL Blackbird export in fixtures/.

    python3 test_bb_import.py            # offline; no adapter, no JVM, no network
    python3 test_bb_import.py -v

The offline tests carry their own copy of the powermodel activity dictionary (captured from a live
`GET /introspect?model=powermodel`, see POWERMODEL_TYPES) so they never need the adapter. The one
test that does need it skips cleanly when it is unreachable.

The load-bearing test here is `TestParentRule`. Everything else fails loudly when it breaks; the
`parent == null` rule fails SILENTLY -- importing a decomposition child as a directive produces a
plan that loads, validates, and simulates, just with activities counted twice.
"""
import json
import os
import unittest
import urllib.error
import urllib.request
from datetime import datetime, timezone

import bb_import
from bb_import import ModelSchema, convert, coerce_value, map_kv_schema, us_to_pg_interval

HERE = os.path.dirname(os.path.abspath(__file__))
FIXTURE = os.path.join(HERE, "fixtures", "powermodel-export.plan.json")
ADAPTER_URL = os.environ.get("BB_ADAPTER_URL", "http://localhost:5011")

STRING = {"type": "string"}
DURATION = {"type": "duration"}
STRING_LIST = {"type": "series", "items": STRING}
STRING_MAP = {"type": "series", "items": {"type": "struct", "items": {"key": STRING, "value": STRING}}}

# Verbatim from `GET /introspect?model=powermodel` -- only the types the fixture uses, plus the two
# it exercises indirectly. `ActivityThree.d` is the model's one OPTIONAL parameter (default 1 min).
POWERMODEL_TYPES = {
    "SciencePass":    ([], {}, {}),
    "CollectScience": (["d"], {"d": DURATION}, {}),
    "Downlink":       (["d"], {"d": DURATION}, {}),
    "ActivityOne":    (["d"], {"d": DURATION}, {}),
    "ActivityTwo":    (["amount"], {"amount": {"type": "real"}}, {}),
    "ActivityThree":  (["d", "stringList"], {"d": DURATION, "stringList": STRING_LIST}, {"d": 60_000_000}),
    "ActivityFour":   (["d", "stringMap"], {"d": DURATION, "stringMap": STRING_MAP}, {}),
    "ActivityEight":  (["first", "second"], {"first": STRING, "second": STRING}, {}),
    "ActivityNine":   (["endTime"], {"endTime": STRING}, {}),
}

# What the fixture actually contains, restated here so the tests pin the file rather than read
# whatever it happens to say. 11 activities; the 4 with a non-null parent are decomposition spans.
EXPECTED_DROPS = {
    ("6f5c8b79-f2e1-4f72-9b41-5c670e81afcb", "CollectScience"),
    ("f86a845c-c650-4130-a408-cfd2322d1dd0", "Downlink"),
    ("1b4f113f-e588-4bd3-b617-6361d92712f8", "ActivityOne"),
    ("2b657162-aab7-467c-8297-9f45d4d6b77c", "ActivityOne"),
}
EXPECTED_DIRECTIVES = [
    ("SciencePass",   "01:00:00"),
    ("ActivityOne",   "02:00:00"),
    ("ActivityEight", "03:00:00"),
    ("ActivityTwo",   "04:00:00"),
    ("ActivityThree", "05:00:00"),
    ("ActivityFour",  "06:00:00"),
    ("ActivityNine",  "07:00:00"),
]


def stub_schema(types=None):
    s = ModelSchema("test stub")
    for typ, (order, schemas, defaults) in (types or POWERMODEL_TYPES).items():
        s.param_order[typ] = list(order)
        s.param_schemas[typ] = dict(schemas)
        # Mirrors ModelSchema.from_url: defaults are already in PlanDev's value space, so the
        # bbtype that effective_args uses to pick a coerce_default conversion is the pass-through.
        s.param_types[typ] = [(pn, "string") for pn in order]
        s.param_defaults[typ] = dict(defaults)
    return s


def load_fixture():
    with open(FIXTURE) as f:
        return json.load(f)


def convert_fixture(**kw):
    return convert(load_fixture(), stub_schema(), plan_name="powermodel-export", **kw)


class TestParentRule(unittest.TestCase):
    """The rule that has no downstream check: only `parent == null` becomes a directive.

    A decomposition child imported as a directive runs AND is regenerated by its parent. The plan
    still loads, still validates, still simulates -- it is just wrong, with no symptom. So the rule
    is pinned from both directions: nothing with a parent gets out, and the dropped set is exactly
    the set that has one.
    """

    def setUp(self):
        self.plan = load_fixture()
        self.transfer, self.report = convert(self.plan, stub_schema())
        self.by_id = {a["id"]: a for a in self.plan["activities"]}

    def test_no_child_is_ever_emitted(self):
        for a in self.transfer["activities"]:
            bb_id = a["metadata"]["blackbirdId"]
            self.assertIn(bb_id, self.by_id, "emitted an activity that is not in the source file")
            self.assertIsNone(self.by_id[bb_id]["parent"],
                              "emitted %s (%s), which is a decomposition child of %s"
                              % (a["type"], bb_id, self.by_id[bb_id]["parent"]))

    def test_dropped_set_is_exactly_the_non_null_parent_set(self):
        have_parent = {a["id"] for a in self.plan["activities"] if a.get("parent") is not None}
        self.assertEqual({d["id"] for d in self.report["dropped"]}, have_parent)
        for d in self.report["dropped"]:
            self.assertIn("decomposition child of", d["reason"])

    def test_every_top_level_activity_is_emitted(self):
        top = [a["id"] for a in self.plan["activities"] if a.get("parent") is None]
        self.assertEqual([a["metadata"]["blackbirdId"] for a in self.transfer["activities"]], top)

    def test_no_type_or_time_heuristic_could_have_worked(self):
        """Why `parent` and nothing else: the fixture is built so the alternatives all fail."""
        acts = self.plan["activities"]
        top_types = {a["type"] for a in acts if a.get("parent") is None}
        child_types = {a["type"] for a in acts if a.get("parent") is not None}
        self.assertTrue(top_types & child_types,
                        "fixture no longer has a type that is both a directive and a child")
        by_id = {a["id"]: a for a in acts}
        self.assertTrue(any(a["start"] == by_id[a["parent"]]["start"]
                            for a in acts if a.get("parent") in by_id),
                        "fixture no longer has a child starting at the same instant as its parent")


class TestCounts(unittest.TestCase):
    def test_seven_out_four_dropped(self):
        plan = load_fixture()
        transfer, report = convert(plan, stub_schema())
        self.assertEqual(len(plan["activities"]), 11)
        self.assertEqual(len(transfer["activities"]), 7)
        self.assertEqual(report["activities"], 7)
        self.assertEqual(len(report["dropped"]), 4)

    def test_dropped_are_exactly_the_expected_uuids_and_types(self):
        _, report = convert_fixture()
        self.assertEqual({(d["id"], d["type"]) for d in report["dropped"]}, EXPECTED_DROPS)

    def test_ids_are_sequential_and_index_aligned(self):
        transfer, _ = convert_fixture()
        self.assertEqual([a["id"] for a in transfer["activities"]], list(range(1, 8)))

    def test_constant_directive_fields(self):
        transfer, _ = convert_fixture()
        for a in transfer["activities"]:
            self.assertIsNone(a["anchor_id"])
            self.assertTrue(a["anchored_to_start"])
            self.assertEqual(a["tags"], [])
            self.assertEqual(a["name"], a["type"])
            self.assertEqual(set(a), {"anchor_id", "anchored_to_start", "arguments", "id",
                                      "metadata", "name", "start_offset", "tags", "type"})
        self.assertEqual(transfer["simulation_arguments"], {})

    def test_metadata_carries_the_blackbird_id_and_omits_empty_notes(self):
        plan = load_fixture()
        transfer, _ = convert(plan, stub_schema())
        top = [a for a in plan["activities"] if a.get("parent") is None]
        for directive, src in zip(transfer["activities"], top):
            self.assertEqual(directive["metadata"], {"blackbirdId": src["id"]})  # fixture notes are ""
        plan["activities"][0]["notes"] = "  keep me  "
        transfer, _ = convert(plan, stub_schema())
        self.assertEqual(transfer["activities"][0]["metadata"]["blackbirdNotes"], "  keep me  ")


class TestPlanWindow(unittest.TestCase):
    def test_plan_start_is_the_utc_day_floor_of_the_first_directive(self):
        _, report = convert_fixture()
        self.assertEqual(report["planStart"], "2024-01-01T00:00:00Z")

    def test_offsets_are_one_through_seven_hours_and_none_negative(self):
        transfer, _ = convert_fixture()
        self.assertEqual([(a["type"], a["start_offset"]) for a in transfer["activities"]],
                         EXPECTED_DIRECTIVES)
        for a in transfer["activities"]:
            self.assertFalse(a["start_offset"].startswith("-"), a["start_offset"])

    def test_suggested_duration_covers_the_last_directive_plus_a_day(self):
        _, report = convert_fixture()
        self.assertEqual(report["suggestedDuration"], "1 days 00:00:00")

    def test_transfer_prefills_the_import_dialog(self):
        """The gateway ignores these; PlanDev's UI reads them to prefill the form it does use."""
        transfer, _ = convert_fixture()
        self.assertEqual(transfer["start_time"], "2024-01-01T00:00:00+00:00")
        self.assertEqual(transfer["duration"], "1 days 00:00:00")
