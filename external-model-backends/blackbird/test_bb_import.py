class TestCoercion(unittest.TestCase):
    def setUp(self):
        transfer, self.report = convert_fixture()
        self.args = {a["type"]: a["arguments"] for a in transfer["activities"]}

    def test_duration_becomes_integer_microseconds(self):
        self.assertEqual(self.args["ActivityOne"], {"d": 3_600_000_000})           # 01:00:00.000000
        self.assertEqual(self.args["ActivityFour"]["d"], 600_000_000)              # 00:10:00.000000
        self.assertIsInstance(self.args["ActivityOne"]["d"], int)
        self.assertNotIsInstance(self.args["ActivityOne"]["d"], bool)

    def test_float_stays_a_number(self):
        self.assertEqual(self.args["ActivityTwo"], {"amount": 42.5})
        self.assertIsInstance(self.args["ActivityTwo"]["amount"], float)

    def test_string_stays_bare(self):
        self.assertEqual(self.args["ActivityEight"], {"first": "Earth", "second": "x"})

    def test_time_is_carried_verbatim_as_day_of_year(self):
        # NOT normalized to ISO-8601: Blackbird's own parser rejects that on the way back in.
        self.assertEqual(self.args["ActivityNine"], {"endTime": "2024-001T08:00:00.000000"})

    def test_list_of_string_stays_a_json_array(self):
        self.assertEqual(self.args["ActivityThree"]["stringList"], ["a", "b", "c"])

    def test_map_becomes_a_key_value_series(self):
        # Blackbird writes {"k1":"v1","k2":"v2"}; PlanDev/merlin's MapValueMapper wants this.
        self.assertEqual(self.args["ActivityFour"]["stringMap"],
                         [{"key": "k1", "value": "v1"}, {"key": "k2", "value": "v2"}])

    def test_no_argument_is_left_in_blackbird_shape(self):
        for typ, args in self.args.items():
            for name, value in args.items():
                self.assertNotIsInstance(value, dict, "%s.%s is still a native JSON map" % (typ, name))

    def test_arguments_follow_the_models_declared_order(self):
        self.assertEqual(list(self.args["ActivityEight"]), ["first", "second"])
        self.assertEqual(list(self.args["ActivityFour"]), ["d", "stringMap"])

    def test_the_only_fixture_warning_is_the_absolute_time_parameter(self):
        self.assertEqual(len(self.report["warnings"]), 1, self.report["warnings"])
        w = self.report["warnings"][0]
        self.assertEqual(w["type"], "ActivityNine")
        self.assertEqual(w["index"], 10)               # index in the SOURCE activities array
        self.assertIn("ABSOLUTE", w["message"])


class TestCoercionUnits(unittest.TestCase):
    def test_map_schema_detection(self):
        self.assertEqual(map_kv_schema(STRING_MAP), (STRING, STRING))
        self.assertIsNone(map_kv_schema(STRING_LIST))
        self.assertIsNone(map_kv_schema(STRING))

    def test_nested_containers_recurse(self):
        list_of_dur = {"type": "series", "items": DURATION}
        self.assertEqual(coerce_value(list_of_dur, ["00:00:01.000000", "1T00:00:00.000000"]),
                         [1_000_000, 86_400_000_000])
        map_to_list = {"type": "series", "items": {"type": "struct", "items": {
            "key": STRING, "value": STRING_LIST}}}
        self.assertEqual(coerce_value(map_to_list, {"k": ["a", "b"]}),
                         [{"key": "k", "value": ["a", "b"]}])

    def test_scalar_conversions(self):
        self.assertEqual(coerce_value({"type": "int"}, 3), 3)
        self.assertEqual(coerce_value({"type": "int"}, "3"), 3)
        self.assertIs(coerce_value({"type": "boolean"}, "true"), True)
        self.assertEqual(coerce_value({"type": "real"}, 1), 1.0)
        self.assertEqual(coerce_value({"type": "variant"}, "Idle"), "Idle")

    def test_bad_values_raise_rather_than_pass_through(self):
        for schema, value in [(DURATION, "not-a-duration"), (DURATION, {}),
                              (STRING_LIST, "a,b,c"), (STRING_MAP, ["k1"]),
                              ({"type": "int"}, "x"), ({"type": "boolean"}, 1), (STRING, 5)]:
            with self.assertRaises(bb_import.CoercionError):
                coerce_value(schema, value)

    def test_interval_formatting(self):
        self.assertEqual(us_to_pg_interval(0), "00:00:00")
        self.assertEqual(us_to_pg_interval(3_600_000_000), "01:00:00")
        self.assertEqual(us_to_pg_interval(1_500), "00:00:00.001500")
        self.assertEqual(us_to_pg_interval(90_061_000_000), "1 days 01:01:01")
        # Postgres signs every component; `-1 days 02:00:00` would read back as -22h.
        self.assertEqual(us_to_pg_interval(-90_000_000_000), "-1 days -01:00:00")


class TestWarningsAndDrops(unittest.TestCase):
    def test_unregistered_type_is_dropped(self):
        plan = load_fixture()
        plan["activities"][3]["type"] = "NotAThing"
        transfer, report = convert(plan, stub_schema())
        self.assertEqual(len(transfer["activities"]), 6)
        self.assertTrue(any(d["type"] == "NotAThing" and "not registered" in d["reason"]
                            for d in report["dropped"]))

    def test_undeclared_parameter_is_dropped_with_a_warning(self):
        plan = load_fixture()
        plan["activities"][3]["parameters"].append({"name": "bogus", "type": "string", "value": "z"})
        transfer, report = convert(plan, stub_schema())
        self.assertNotIn("bogus", transfer["activities"][1]["arguments"])
        self.assertTrue(any("'bogus' is not declared" in w["message"] for w in report["warnings"]))

    def test_absent_declared_parameter_is_filled_from_the_default(self):
        plan = load_fixture()
        three = next(a for a in plan["activities"] if a["type"] == "ActivityThree")
        three["parameters"] = [p for p in three["parameters"] if p["name"] != "d"]
        transfer, report = convert(plan, stub_schema())
        args = next(a["arguments"] for a in transfer["activities"] if a["type"] == "ActivityThree")
        self.assertEqual(args["d"], 60_000_000)
        self.assertTrue(any("filled from the model default" in w["message"] for w in report["warnings"]))

    def test_absent_declared_parameter_with_no_default_says_so(self):
        plan = load_fixture()
        one = next(a for a in plan["activities"] if a["type"] == "ActivityOne")
        one["parameters"] = []
        transfer, report = convert(plan, stub_schema())
        self.assertEqual(transfer["activities"][1]["arguments"], {})
        self.assertTrue(any("declares no default" in w["message"] for w in report["warnings"]))

    def test_uncoercible_value_warns_and_omits_the_argument(self):
        plan = load_fixture()
        one = next(a for a in plan["activities"] if a["type"] == "ActivityOne")
        one["parameters"][0]["value"] = "half past four"
        transfer, report = convert(plan, stub_schema())
        self.assertEqual(transfer["activities"][1]["arguments"], {})
        self.assertTrue(any("argument omitted" in w["message"] for w in report["warnings"]))

    def test_dangling_parent_uuid_warns_and_still_drops(self):
        plan = load_fixture()
        child = next(a for a in plan["activities"] if a["type"] == "CollectScience")
        child["parent"] = "00000000-0000-0000-0000-000000000000"
        transfer, report = convert(plan, stub_schema())
        self.assertEqual(len(transfer["activities"]), 7)
        self.assertTrue(any("not present in the file" in w["message"] for w in report["warnings"]))

    def test_duplicate_id_warns(self):
        plan = load_fixture()
        plan["activities"][3]["id"] = plan["activities"][4]["id"]
        _, report = convert(plan, stub_schema())
        self.assertTrue(any("appears more than once" in w["message"] for w in report["warnings"]))

    def test_model_drift_since_export_warns(self):
        """The file records the type each value was written as; a changed model must not be silent."""
        types = dict(POWERMODEL_TYPES)
        types["ActivityTwo"] = (["amount"], {"amount": {"type": "int"}}, {})
        _, report = convert(load_fixture(), stub_schema(types))
        self.assertTrue(any("declares schema" in w["message"] for w in report["warnings"]))

    def test_warning_index_is_the_source_index_not_the_output_index(self):
        plan = load_fixture()
        plan["activities"][10]["parameters"].append({"name": "nope", "type": "string", "value": "1"})
        _, report = convert(plan, stub_schema())
        self.assertEqual([w["index"] for w in report["warnings"] if "'nope'" in w["message"]], [10])

    def test_a_plan_with_no_activities_key_is_rejected(self):
        with self.assertRaises(ValueError):
            convert({}, stub_schema())

    def test_a_plan_of_only_children_needs_an_explicit_start(self):
        plan = {"activities": [a for a in load_fixture()["activities"] if a.get("parent")]}
        with self.assertRaises(ValueError):
            convert(plan, stub_schema())
        transfer, report = convert(plan, stub_schema(),
                                   plan_start=datetime(2024, 1, 1, tzinfo=timezone.utc))
        self.assertEqual(transfer["activities"], [])
        self.assertEqual(len(report["dropped"]), 4)


def adapter_reachable():
    try:
        urllib.request.urlopen(ADAPTER_URL + "/models", timeout=3).read()
        return True
    except Exception:
        return False


@unittest.skipUnless(adapter_reachable(), "no bb_service at %s" % ADAPTER_URL)
class TestAgainstLiveAdapter(unittest.TestCase):
    """Round trip: convert the fixture, then hand the directives back to Blackbird.

    Requires a running adapter, so it skips by default. Nothing above depends on it.
    """

    @classmethod
    def setUpClass(cls):
        cls.schema = ModelSchema.from_url(ADAPTER_URL, "powermodel")

    def test_live_introspection_matches_the_stubbed_dictionary(self):
        stub = stub_schema()
        for typ in POWERMODEL_TYPES:
            self.assertIn(typ, self.schema, "%s is no longer registered" % typ)
            self.assertEqual(self.schema.param_order[typ], stub.param_order[typ], typ)
            self.assertEqual(self.schema.param_schemas[typ], stub.param_schemas[typ], typ)
            self.assertEqual(self.schema.param_defaults[typ], stub.param_defaults[typ], typ)

    def test_converted_directives_simulate_back_to_eleven_spans(self):
        transfer, report = convert(load_fixture(), self.schema)
        directives = [{"id": a["id"], "type": a["type"], "arguments": a["arguments"],
                       "startOffset": bb_import.bb_dur_to_us(a["start_offset"].replace(" days ", "T"))}
                      for a in transfer["activities"]]
        req = urllib.request.Request(
            ADAPTER_URL + "/simulate?model=powermodel",
            data=json.dumps({"planStart": report["planStart"], "duration": 86_400_000_000,
                             "configuration": {}, "directives": directives}).encode(),
            headers={"Content-Type": "application/json"}, method="POST")
        with urllib.request.urlopen(req, timeout=300) as r:
            sim = json.load(r)
        self.assertNotIn("error", sim, sim.get("error"))
        spans = sim["spans"]
        # 7 directives + the 4 decomposition children the converter correctly refused to import.
        self.assertEqual(len(spans), 11, [s["type"] for s in spans])
        self.assertEqual(sorted(s["type"] for s in spans),
                         sorted([t for t, _ in EXPECTED_DIRECTIVES]
                                + ["CollectScience", "Downlink", "ActivityOne", "ActivityOne"]))
        self.assertEqual(sorted(s["directiveId"] for s in spans if s.get("directiveId")),
                         list(range(1, 8)))


